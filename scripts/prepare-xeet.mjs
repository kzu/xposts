// Makes @xeet/core loadable on Cloudflare Workers.
//
// The npm package ships wasm-bindgen's `nodejs` glue, which reads the .wasm
// from disk with `require("fs")`. Workers have no filesystem, so this script
// writes a copy of the glue that instantiates the module wrangler imports
// instead, and copies the lazy font packs (39 MB, too large for the Worker
// bundle) to the static assets directory the Worker reads them from.
//
// Output is generated and git-ignored; `npm install` runs this script.

import { copyFileSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
const pkgDir = join(dirname(require.resolve("@xeet/core")), "..");
const wasmDir = join(pkgDir, "wasm");
const generated = join(root, "src", "render", "generated");
const fontsOut = join(root, "assets", "xeet-fonts");
mkdirSync(generated, { recursive: true });
mkdirSync(fontsOut, { recursive: true });

const glue = readFileSync(join(wasmDir, "xeet_wasm.js"), "utf8");
const marker = "const wasmPath = require('path')";
const cut = glue.indexOf(marker);
if (cut < 0 || /require\(/.test(glue.slice(0, cut))) {
  throw new Error(
    "prepare-xeet: the @xeet/core glue changed shape; update scripts/prepare-xeet.mjs for this version",
  );
}
const version = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8")).version;

writeFileSync(
  join(generated, "xeet-wasm.js"),
  `// GENERATED by scripts/prepare-xeet.mjs from @xeet/core@${version}. Do not edit.
import wasmModule from "./xeet_wasm_bg.wasm";

let cached;

/** Instantiates the xeet module once per isolate and returns its wasm-bindgen exports. */
export function loadXeetWasm() {
  if (cached) return cached;
  const exports = {};
  (function () {
${glue.slice(0, cut)}
const wasmInstance = new WebAssembly.Instance(wasmModule, __wbg_get_imports());
wasm = wasmInstance.exports;
wasm.__wbindgen_start();
  })();
  cached = exports;
  return cached;
}

export const XEET_VERSION = ${JSON.stringify(version)};
`.replace("let WASM_VECTOR_LEN = 0;", "let WASM_VECTOR_LEN = 0;\nlet wasm;"),
);

copyFileSync(join(wasmDir, "xeet_wasm_bg.wasm"), join(generated, "xeet_wasm_bg.wasm"));
copyFileSync(join(wasmDir, "fonts", "packs.json"), join(generated, "packs.json"));
// The package's export map hides its font-pack loader, so it is copied too.
copyFileSync(join(pkgDir, "src", "fonts.js"), join(generated, "fonts.js"));
writeFileSync(
  join(generated, "xeet-wasm.d.ts"),
  `export interface XeetWasm {
  call(op: number, request: string): Uint8Array;
  upstream_version(): string;
  register_font(file: string, bytes: Uint8Array): void;
  missing_packs(request: string): string;
  packs_for(request: string): string;
  resolve(input: string, options: string, host: unknown): Promise<string>;
  resolve_links(url: string, options: string, host: unknown): Promise<string>;
}
export function loadXeetWasm(): XeetWasm;
export const XEET_VERSION: string;
`,
);
writeFileSync(
  join(generated, "fonts.d.ts"),
  `export function sha256Hex(bytes: Uint8Array): Promise<string>;
export function createFontPacks(options: {
  manifest: unknown;
  read: (name: string) => Uint8Array | Promise<Uint8Array>;
  hash: (bytes: Uint8Array) => string | Promise<string>;
  register: (file: string, bytes: Uint8Array) => void;
  missingPacks: (requestJson: string) => string;
}): {
  names: string[];
  loaded(): string[];
  ensure(request: unknown): Promise<string[]>;
  loadAll(): Promise<void>;
};
`,
);
for (const file of readdirSync(join(wasmDir, "fonts"))) {
  if (file.endsWith(".bin")) copyFileSync(join(wasmDir, "fonts", file), join(fontsOut, file));
}
console.log(`prepare-xeet: @xeet/core@${version} ready for Workers`);
